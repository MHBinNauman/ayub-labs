/**
 * Rules for the photo pipeline (`pnpm images`): which files are photos, how
 * wide a copy may be, what it is called, and the generated data file. Pure:
 * scripts/optimize-images.ts does the file I/O and the resizing, so
 * everything here is unit-testable.
 */
import type { MediaFile } from "@/data/media.generated";

/** Folders under public/images that hold originals. Same names as MediaItem.kind. */
export const IMAGE_FOLDERS = ["stock", "real"] as const;
export type ImageFolder = (typeof IMAGE_FOLDERS)[number];

/** Resized copies go in this folder next to the originals. Only these are committed. */
export const OUTPUT_FOLDER = "optimized";

export const JPEG_QUALITY = 78;
/** Width of the blurred preview, in pixels. Keep it tiny: it is inlined in the HTML. */
export const BLUR_WIDTH = 16;

export function isPhoto(fileName: string): boolean {
  return /\.(jpe?g|png)$/i.test(fileName);
}

/** Heroes fill the screen; everything else is a card or a banner. */
export function maxWidth(fileName: string): number {
  return /^hero-/i.test(fileName) ? 2400 : 1600;
}

/**
 * Name of the optimised copy: a URL-safe version of the original's name.
 * PNG is kept only for images with transparency.
 */
export function outputName(
  fileName: string,
  { transparent }: { transparent: boolean },
): string {
  const base = fileName
    .replace(/\.[^.]+$/, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  if (!base) throw new Error(`"${fileName}" has no usable name; rename it`);
  return `${base}.${transparent ? "png" : "jpg"}`;
}

/** The public URL of an optimised copy. */
export function outputSrc(folder: ImageFolder, name: string): string {
  return `/images/${folder}/${OUTPUT_FOLDER}/${name}`;
}

/**
 * Originals whose copies would overwrite each other, as readable problems.
 * Compared without the extension, so "a.jpg" and "a.png" always clash.
 */
export function nameClashes(fileNames: readonly string[]): string[] {
  const seen = new Map<string, string>();
  const clashes: string[] = [];
  for (const fileName of fileNames) {
    const key = outputName(fileName, { transparent: false });
    const first = seen.get(key);
    if (first) clashes.push(`"${first}" and "${fileName}"`);
    else seen.set(key, fileName);
  }
  return clashes;
}

/** The whole of src/data/media.generated.ts. Sorted, so reruns are identical. */
export function renderGeneratedMedia(files: readonly MediaFile[]): string {
  const entries = [...files]
    .sort((a, b) => (a.src < b.src ? -1 : a.src > b.src ? 1 : 0))
    .map((file) => `  ${JSON.stringify(file.src)}: ${JSON.stringify(file)},\n`)
    .join("");

  return `/**
 * GENERATED by scripts/optimize-images.ts from the "${OUTPUT_FOLDER}" folders in public/images.
 * Do not edit by hand: add or replace a photo and run \`pnpm images\`.
 */
export type MediaFile = {
  src: string;
  width: number;
  height: number;
  /** Tiny inline preview shown while the photo loads. */
  blurDataURL: string;
};

/** Every optimised photo, keyed by its public URL. */
export const generatedMedia: Record<string, MediaFile> = {
${entries}};
`;
}
